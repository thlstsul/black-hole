/// 将英文标点符号映射为中文标点符号。
///
/// 当输入法激活且当前无编码输入时，按下英文标点键直接输出对应的中文标点。
/// 若当前有编码输入，则先提交当前候选再追加中文标点。
pub fn convert_punctuation(ch: char) -> Option<char> {
    match ch {
        ',' => Some('，'),
        '.' => Some('。'),
        '/' => Some('、'),
        ';' => Some('；'),
        '\'' => Some('‘'),
        '[' => Some('【'),
        ']' => Some('】'),
        '`' => Some('·'),
        '-' => Some('－'),
        '=' => Some('＝'),
        '!' => Some('！'),
        '#' => Some('＃'),
        '$' => Some('￥'),
        '%' => Some('％'),
        '^' => Some('…'),
        '&' => Some('＆'),
        '*' => Some('×'),
        '(' => Some('（'),
        ')' => Some('）'),
        '_' => Some('—'),
        '+' => Some('＋'),
        '{' => Some('｛'),
        '}' => Some('｝'),
        '|' => Some('｜'),
        ':' => Some('：'),
        '"' => Some('“'),
        '<' => Some('《'),
        '>' => Some('》'),
        '?' => Some('？'),
        '\\' => Some('、'),
        '@' => Some('·'),
        '~' => Some('～'),
        _ => None,
    }
}
